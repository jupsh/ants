#!/usr/bin/env node
// The Decisions log (docs/log/) and the contamination log (docs/contamination/)
// as records: one Markdown file per entry, frontmatter + the entry verbatim.
// The files are the source of truth; each folder's README.md is generated.
// Kept by the lead agent (CLAUDE.md); other agents report and never write here.
// STATUS 2026-10-18 ≈ 16:32.
//
//   node docs/records.mjs                                  regenerate both indexes
//   node docs/records.mjs log new "<title>" --kind k       new entry, stamped with the current UTC time
//   node docs/records.mjs contamination new "<title>" --role r
//   node docs/records.mjs log find '<MongoDB-style JSON query>' [--sort [-]field] [--fields a,b] [--json]
//     e.g. log find '{"kind":"reading","date":{"$gte":"2026-10-18"}}'   ·   log find '{"body":{"$regex":"C2"}}'
//   node docs/records.mjs check        fields, ids, file names; no dated entries left in docs/STATUS.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cell, die, findAndPrint, parseArgs, readFolder, slugify, writeRecord } from '../scripts/records.mjs';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const KINDS = [
  ['decision', 'a decision (the user\'s, or delegated)'],
  ['design', 'a design or pre-registration fixed before a run, or its amendment'],
  ['reading', 'a result read (against its rule, or descriptively)'],
  ['run', 'a run launched, code or tooling built'],
  ['review', 'guidance or a review (pasted, or a lead-agent review)'],
  ['correction', 'a defect or an error found and corrected'],
  ['note', 'anything else'],
];
const LOG = {
  name: 'log',
  dir: path.join(ROOT, 'docs/log'),
  re: /^(\d{4}-\d{2}-\d{2})-(\d{4})-[a-z0-9-]+\.md$/,
  prefix: 'D',
};
const CON = {
  name: 'contamination',
  dir: path.join(ROOT, 'docs/contamination'),
  re: /^X\d{3}-[a-z0-9-]+\.md$/,
  prefix: 'X',
};
// A dated entry header as the Decisions log wrote them (for the STATUS check).
const ENTRY = /^(- )?\*\*20\d\d-\d\d-\d\d (≈ \d|night|evening|late|morning)/;

function read(c) {
  const { records, problems } = readFolder(c.dir, c.re);
  const ids = new Map();
  for (const r of records) {
    if (!new RegExp(`^${c.prefix}\\d{3}$`).test(r.id ?? '')) problems.push(`${r.name}: bad id "${r.id}"`);
    if (ids.has(r.id)) problems.push(`duplicate id ${r.id}: ${ids.get(r.id)}, ${r.name}`);
    ids.set(r.id, r.name);
    if (!r.title) problems.push(`${r.name}: no title`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date ?? '')) problems.push(`${r.name}: date is not YYYY-MM-DD`);
    if (c === LOG) {
      if (!KINDS.some(([k]) => k === r.kind)) problems.push(`${r.name}: unknown kind "${r.kind}"`);
      const m = r.name.match(c.re);
      if (m && (m[1] !== r.date || m[2] !== (r.time ?? '').replace(':', ''))) problems.push(`${r.name}: file name does not match date ${r.date} / time ${r.time}`);
    } else if (!r.role) problems.push(`${r.name}: no role`);
  }
  return { records: records.sort((a, b) => a.id.localeCompare(b.id)), problems };
}

function nextId(c, records) {
  const n = Math.max(0, ...records.map((r) => Number(String(r.id).slice(1)) || 0)) + 1;
  return `${c.prefix}${String(n).padStart(3, '0')}`;
}

function renderIndexes() {
  const all = [];
  const out = [];
  {
    const { records, problems } = read(LOG);
    const lines = [
      '<!-- Generated by `node docs/records.mjs` from the entry files; do not edit. -->',
      '# Decisions log',
      '',
      'One file per dated entry, newest first; each file holds the entry verbatim. Entries before 2026-10-17 ≈ 13:10',
      'UTC are in `docs/archive/`. New entry: `node docs/records.mjs log new "<title>" --kind k` (stamps the UTC time).',
      'Query: `node docs/records.mjs log find \'{"kind":"reading","body":{"$regex":"C2"}}\'`.',
      '',
      `Kinds: ${KINDS.map(([k, d]) => `**${k}** ${d}`).join('; ')}.`,
      '',
      '| id | date | time | kind | entry |',
      '|---|---|---|---|---|',
      ...[...records].reverse().map((r) => `| ${r.id} | ${r.date} | ${r.time ?? ''} | ${r.kind} | [${cell(r.title)}](${r.name}) |`),
    ];
    if (problems.length) lines.push('', '## Problems', ...problems.map((p) => `- ${p}`));
    out.push({ file: path.join(LOG.dir, 'README.md'), text: lines.join('\n') + '\n', msg: `docs/log/README.md: ${records.length} entries` });
    all.push(...problems);
  }
  {
    const { records, problems } = read(CON);
    const lines = [
      '<!-- Generated by `node docs/records.mjs` from the entry files; do not edit. -->',
      '# Contamination log: which "withheld" results have been seen',
      '',
      'One file per source or exposure event, holding its entry verbatim. Roles of data: `docs/STATUS.md` § Evidence',
      'policy. New entry: `node docs/records.mjs contamination new "<title>" --role r`; amend an existing source\'s file',
      'with a dated line rather than adding a second one.',
      '',
      '| id | role | entry | first logged |',
      '|---|---|---|---|',
      ...records.map((r) => `| ${r.id} | ${cell(r.role)} | [${cell(r.title)}](${r.name}) | ${r.date} |`),
    ];
    if (problems.length) lines.push('', '## Problems', ...problems.map((p) => `- ${p}`));
    out.push({ file: path.join(CON.dir, 'README.md'), text: lines.join('\n') + '\n', msg: `docs/contamination/README.md: ${records.length} entries` });
    all.push(...problems);
  }
  return { out, problems: all };
}

function writeIndexes() {
  const { out, problems } = renderIndexes();
  for (const o of out) {
    fs.writeFileSync(o.file, o.text);
    console.log(o.msg);
  }
  for (const p of problems) console.error(`problem: ${p}`);
}

function cmdNew(c, pos, opt) {
  const title = pos[0];
  if (!title) die(`usage: ${c.name} new "<title>" ${c === LOG ? '--kind k' : '--role r'}`);
  const { records } = read(c);
  const id = nextId(c, records);
  const now = new Date();
  const date = now.toISOString().slice(0, 10);
  const time = now.toISOString().slice(11, 16);
  if (c === LOG) {
    if (!KINDS.some(([k]) => k === opt.kind)) die(`--kind must be one of ${KINDS.map(([k]) => k).join(', ')}`);
    const file = path.join(c.dir, `${date}-${time.replace(':', '')}-${slugify(title)}.md`);
    writeRecord(file, [['id', id], ['date', date], ['time', time], ['kind', opt.kind], ['title', title]],
      `- **${date} ≈ ${time} UTC — ${title}.**\n  <The entry: what, why, the rule or reading, the numbers.>`);
    console.log(`created ${path.relative(ROOT, file)}`);
  } else {
    if (!opt.role) die('--role is required (fit, development, held-out, source, methods, …)');
    const file = path.join(c.dir, `${id}-${slugify(title)}.md`);
    writeRecord(file, [['id', id], ['title', title], ['date', date], ['role', opt.role]],
      `- **${title} (${date} ≈ ${time} UTC):** <what was seen, by whom, and what it changes>`);
    console.log(`created ${path.relative(ROOT, file)}`);
  }
}

function cmdFind(c, pos, opt) {
  const docs = read(c).records.map(({ file, ...r }) => r);
  findAndPrint(docs, pos[0], opt, (d) =>
    c === LOG ? `${d.id}  ${d.date} ${d.time ?? ''}  ${String(d.kind).padEnd(10)} ${d.title}` : `${d.id}  ${String(d.role).padEnd(14)} ${d.title}`,
  );
}

function cmdCheck() {
  const problems = [...read(LOG).problems, ...read(CON).problems];
  const status = fs.readFileSync(path.join(ROOT, 'docs/STATUS.md'), 'utf8').split('\n');
  status.forEach((l, i) => {
    if (ENTRY.test(l)) problems.push(`docs/STATUS.md:${i + 1}: a dated entry belongs in docs/log/ (node docs/records.mjs log new …): ${l.slice(0, 80)}`);
  });
  for (const o of renderIndexes().out)
    if (!fs.existsSync(o.file) || fs.readFileSync(o.file, 'utf8') !== o.text) problems.push(`${path.relative(ROOT, o.file)} is out of date: run \`node docs/records.mjs\``);
  for (const p of problems) console.log(`problem: ${p}`);
  console.log(`${read(LOG).records.length} log entries, ${read(CON).records.length} contamination entries; ${problems.length} problems`);
  process.exit(problems.length ? 1 : 0);
}

const { pos, opt } = parseArgs(process.argv.slice(2));
const first = pos.shift();
if (first === 'check') cmdCheck();
else if (first === undefined) writeIndexes();
else {
  const c = first === 'log' ? LOG : first === 'contamination' ? CON : die(`unknown collection or command ${first}`);
  const cmd = pos.shift();
  if (cmd === 'find') cmdFind(c, pos, opt);
  else if (cmd === 'new') {
    cmdNew(c, pos, opt);
    writeIndexes();
  } else die(`unknown command ${cmd}: new | find`);
}
